import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fs from 'node:fs';
const BASE=process.env.SCD_BASE_URL||'http://127.0.0.1:4177';
fs.mkdirSync('test-output',{recursive:true});
const browser=await chromium.launch({headless:true});
const expected=['athlete','family','staff','communications','grow'];
const makeFixture=async page=>{
 await page.route('**/api/newsroom*',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({news:[],partners:[],publicProfiles:[],calendar:{rows:[]},upcomingEvents:[],sportData:{results:[],standings:[]}})}));
 await page.route('**/api/scd*',async r=>{let req={};try{req=JSON.parse(r.request().postData()||'{}')}catch{}
 const data=req.action==='public.calendar'?{rows:[]}:{};
 await r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({ok:true,data})});
 });
};
for(const [label,width,height] of [['mobile',390,844],['desktop',1440,900]]){
 const page=await browser.newPage({viewport:{width,height},deviceScaleFactor:1,acceptDownloads:true,reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',err=>errors.push(String(err)));
 await makeFixture(page);
 const resp=await page.goto(BASE+'/?scdVision=1#pulse',{waitUntil:'networkidle',timeout:30000});
 assert.equal(resp.status(),200,'HTTP '+label);
 await page.locator('[data-testid="one-home"]').waitFor({timeout:10000});
 await page.locator('#scde-launcher .scde-world-toggle').waitFor({timeout:10000});
 const info=await page.evaluate(()=>window.SCDThreeWorlds);
 assert.ok(info&&info.kind==='NATIVE_COMPONENTS','Native adapter missing '+label);
 assert.deepEqual(info.views,expected);
 assert.equal(await page.locator('#view-athlete').count(),1);
 assert.equal(await page.locator('#view-grow').count(),1);
 await page.screenshot({path:'test-output/SCD-three-worlds-home-'+label+'.png',fullPage:true,animations:'disabled'});
 await page.locator('.scde-world-toggle').click();
 await page.locator('#scde-world-drawer [data-scd-route="athlete"]').click();
 await page.locator('#view-athlete.view.active').waitFor();
 await page.locator('#view-athlete [data-scde-athlete="documenti"]').click();
 assert.ok((await page.locator('#view-athlete').innerText()).includes('I miei documenti'));
 await page.screenshot({path:'test-output/SCD-three-worlds-athlete-'+label+'.png',fullPage:true,animations:'disabled'});
 await page.locator('#view-athlete [data-scd-route="family"]').first().click();
 await page.locator('#view-family.view.active').waitFor();
 await page.locator('#view-family [data-scde-family="quote"]').click();
 assert.ok((await page.locator('#view-family').innerText()).includes('Stato delle quote'));
 await page.screenshot({path:'test-output/SCD-three-worlds-family-'+label+'.png',fullPage:true,animations:'disabled'});
 await page.locator('#view-family [data-scd-route="staff"]').first().click();
 await page.locator('#view-staff.view.active').waitFor();
 await page.locator('#view-staff [data-scde-staff="squadre"]').click();
 assert.ok((await page.locator('#view-staff').innerText()).includes('Le mie squadre'));
 await page.screenshot({path:'test-output/SCD-three-worlds-staff-'+label+'.png',fullPage:true,animations:'disabled'});
 await page.locator('#view-staff [data-scd-world-open]').first().click();
 await page.locator('#scde-world-drawer [data-scd-route="grow"]').click();
 await page.locator('#view-grow.view.active').waitFor();
 await page.locator('#view-grow [data-scde-grow-tab="pipeline"]').click();
 assert.ok((await page.locator('#view-grow').innerText()).includes('Pipeline sponsor'));
 assert.equal(await page.locator('#view-grow a[href="./sponsor/"]').count()>0,true,'Existing sponsor route must be linked');
 await page.locator('#view-grow [data-scde-grow-tab="bozza"]').click();
 await page.locator('#scde-grow-form input[name=company]').fill('Partner verifica tecnica');
 await page.locator('#scde-grow-form textarea[name=note]').fill('Richiesta non inviata');
 await page.locator('#scde-grow-form button[type=submit]').click();
 assert.ok((await page.locator('#scde-grow-result').innerText()).includes('Non è stata salvata nel CRM'));
 const downloadPromise=page.waitForEvent('download');await page.locator('[data-scde-download]').click();
 const dl=await downloadPromise;assert.equal(dl.suggestedFilename(),'SCD_GROW_Bozza_Non_Inviata.txt');
 await page.screenshot({path:'test-output/SCD-three-worlds-grow-'+label+'.png',fullPage:true,animations:'disabled'});
 await page.evaluate(()=>window.SCDThreeWorlds.go('communications'));
 await page.locator('#view-communications.view.active').waitFor();
 await page.locator('#view-communications [data-scde-communications="social"]').click();
 assert.equal(await page.locator('#view-communications a[href="https://www.colicoderviese.it/"]').count()>0,true);
 await page.screenshot({path:'test-output/SCD-three-worlds-communications-'+label+'.png',fullPage:true,animations:'disabled'});
 await page.evaluate(()=>window.SCDThreeWorlds.go('desk'));
 await page.locator('#view-desk.view.active').waitFor();
 assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('scde-active')),false,'Existing authenticated desk must not be overwritten');
 assert.equal(await page.locator('#scde-launcher').isVisible(),false,'Demo launcher hidden on existing authenticated desk');
 await page.reload({waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('#view-desk').count(),1);
 assert.deepEqual(errors,[],'Browser errors '+label+': '+errors.join(';'));
 const widths=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
 assert.ok(widths.document<=widths.viewport+2,'Horizontal overflow '+JSON.stringify(widths));
 console.log('THREE WORLDS '+label+' PASS: six screens, native DOM, R20 gate, sponsor link, local draft/export, responsive '+JSON.stringify(widths));
 await page.close();
}
const unchanged=await browser.newPage({viewport:{width:390,height:844}});
await makeFixture(unchanged);
await unchanged.goto(BASE+'/#pulse',{waitUntil:'domcontentloaded'});
assert.equal(await unchanged.locator('#view-grow').count(),0,'Default site remains unchanged without flag');
console.log('DEFAULT SITE INVARIANT PASS');
await unchanged.close();
await browser.close();
