#!/usr/bin/env python3
"""Derive metric-matched fallback faces for the self-hosted club fonts (B3, layout stability).

While an official font is still downloading the browser draws the text with a local font. Without adjustment the
local font is wider or narrower, lines wrap differently and the page jumps when the official font arrives (CLS).
For every family/weight the app imports from @fontsource this script compares the official font with Arial
(metric-identical to Liberation Sans and Helvetica) and writes an @font-face "<Family> Fallback" that points at the
local Arial-compatible font with:
  size-adjust     = average advance of a representative Italian sample in the official font / in Arial
  ascent/descent/line-gap-override = official hhea metrics / size-adjust (same line box as the official font)
Display families (Anton, Big Shoulders Display) also get "<Family> Caps Fallback", measured on capitals only: their
capitals are much narrower than Arial's relative to lower case (0.69 vs 0.83 for Big Shoulders 900), so uppercase
titles use the caps face (styles.css: .uppercase swaps the display stacks).
Nothing official is changed: the official files are only read. Run from apps/superapp:
  python3 scripts/derive-font-fallbacks.py > src/font-fallbacks.css
Inputs: node_modules/@fontsource/<family>/files/<family>-latin-<w>-normal.woff (zlib, no brotli needed) and
/usr/share/fonts/truetype/liberation/LiberationSans-{Regular,Bold}.ttf.
"""
from pathlib import Path

from fontTools.ttLib import TTFont

FAMILIES = {
    # css family: (fontsource package, weights imported in src/styles.css)
    "Fira Sans": ("fira-sans", [400, 500, 600, 700, 800]),
    "Fira Sans Condensed": ("fira-sans-condensed", [500, 600, 700]),
    "Anton": ("anton", [400]),
    "Big Shoulders Display": ("big-shoulders-display", [700, 800, 900]),
    "Barlow": ("barlow", [400, 500, 600, 700]),
}
# Text the app really shows: Italian words, uppercase titles, times and scores.
SAMPLE = (
    "Questa settimana gare in casa a Colico e Dervio, allenamenti, pulmini e calendario della stagione. "
    "ColicoDerviese contro Vis Nova Giussano, sabato ore 18:00, Campo 1. "
    "PRIMI CALCI PULCINI ESORDIENTI GIOVANISSIMI ALLIEVI JUNIORES PRIMA SQUADRA 2026/27 0123456789"
)
CAPS_SAMPLE = "QUESTA SETTIMANA RISULTATI CALENDARIO SUL LED WALL LA TUA SQUADRA I TUOI ORARI IL TUO PULMINO PARTNER 2026/27"
CAPS_FAMILIES = {"Anton", "Big Shoulders Display"}
LIB = Path("/usr/share/fonts/truetype/liberation")
LOCAL = {
    "regular": ['local("Arial")', 'local("ArialMT")', 'local("Liberation Sans")', 'local("LiberationSans")',
                'local("Helvetica")', 'local("Roboto")'],
    "bold": ['local("Arial Bold")', 'local("Arial-BoldMT")', 'local("Liberation Sans Bold")',
             'local("LiberationSans-Bold")', 'local("Helvetica Bold")', 'local("Roboto Bold")'],
}


def avg_advance(font: TTFont, sample: str = SAMPLE) -> float:
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    widths = [hmtx[cmap[ord(c)]][0] / upm for c in sample if ord(c) in cmap]
    return sum(widths) / len(widths)


def pct(v: float) -> str:
    return f"{v * 100:.2f}%"


def main() -> None:
    arial = {k: TTFont(LIB / f"LiberationSans-{n}.ttf") for k, n in (("regular", "Regular"), ("bold", "Bold"))}
    arial_avg = {k: avg_advance(f) for k, f in arial.items()}
    arial_caps = {k: avg_advance(f, CAPS_SAMPLE) for k, f in arial.items()}
    out = [
        "/* GENERATED by scripts/derive-font-fallbacks.py — do not edit by hand.",
        " * Metric-matched local fallbacks for the official self-hosted fonts: while a font downloads the text keeps",
        " * the same width and line box, so the page does not jump when the official font arrives (B3, CLS). */",
    ]

    def face(name: str, base: str, w: int, size: float, f: TTFont) -> str:
        upm = f["head"].unitsPerEm
        hhea = f["hhea"]
        return (
            "@font-face {\n"
            f'  font-family: "{name}";\n'
            f"  src: {', '.join(LOCAL[base])};\n"
            f"  font-weight: {w};\n"
            f"  size-adjust: {pct(size)};\n"
            f"  ascent-override: {pct(hhea.ascent / upm / size)};\n"
            f"  descent-override: {pct(abs(hhea.descent) / upm / size)};\n"
            f"  line-gap-override: {pct(hhea.lineGap / upm / size)};\n"
            "}"
        )

    for family, (pkg, weights) in FAMILIES.items():
        for w in weights:
            f = TTFont(Path("node_modules/@fontsource") / pkg / "files" / f"{pkg}-latin-{w}-normal.woff")
            base = "bold" if w >= 600 or family == "Anton" else "regular"
            out.append(face(f"{family} Fallback", base, w, avg_advance(f) / arial_avg[base], f))
            if family in CAPS_FAMILIES:
                caps = avg_advance(f, CAPS_SAMPLE) / arial_caps[base]
                out.append(face(f"{family} Caps Fallback", base, w, caps, f))
    print("\n".join(out))


if __name__ == "__main__":
    main()
